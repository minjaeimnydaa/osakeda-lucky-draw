import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
process.env.SESSION_SECRET = randomBytes(32).toString('hex');
process.env.ADMIN_PASSWORD = randomBytes(20).toString('hex');
delete process.env.DATABASE_URL; delete process.env.VERCEL;
process.env.NODE_ENV = 'test';
const temp = mkdtempSync(join(tmpdir(),'osakeda-api-'));
process.env.SQLITE_PATH = join(temp,'events.sqlite');
const { default: handler } = await import('../api/index.js');
const { database } = await import('../lib/db.js');
const server = createServer(handler); await new Promise(r => server.listen(0,'127.0.0.1',r));
const origin = `http://127.0.0.1:${server.address().port}`;
after(async () => { await new Promise(r => server.close(r)); (await database()).close(); rmSync(temp,{recursive:true,force:true}); });
const request = (action, data, cookie, customOrigin = origin) => fetch(`${origin}/api/index?action=${action}`, data === undefined ? {headers:{...(cookie ? {cookie} : {})}} : {method:'POST',headers:{'Content-Type':'application/json',Origin:customOrigin,...(cookie ? {cookie} : {})},body:JSON.stringify(data)});
test('HTTP authentication, origin protection and admin-to-customer workflow', async () => {
  assert.equal((await request('admin-data')).status,401);
  assert.equal((await request('draw',{card:1},null,'http://other.example')).status,403);
  assert.equal((await request('login',{password:'incorrect'})).status,401);
  const login = await request('login',{password:process.env.ADMIN_PASSWORD}); assert.equal(login.status,200);
  const adminCookie = login.headers.get('set-cookie').split(';')[0];
  assert.match(adminCookie,/^osk_v2_admin=/);
  assert.match(login.headers.get('set-cookie'),/HttpOnly/);
  assert.match(login.headers.get('set-cookie'),/SameSite=Lax/);
  const baselineAdminCookie = adminCookie.replace(/^osk_v2_admin=/,'osk_admin=');
  assert.equal((await request('admin-data',undefined,baselineAdminCookie)).status,401);
  const data = await (await request('admin-data',undefined,adminCookie)).json();
  const event = data.events[0]; const config = event.config;
  config.prizes.forEach((p,i) => { p.chance = i ? 0 : 100; p.total = i ? 0 : 1; });
  assert.equal((await request('admin-save',{id:event.id,config},adminCookie)).status,200);
  const codesResponse = await request('admin-codes',{id:event.id,customers:['api-customer']},adminCookie);
  const [issued] = await codesResponse.json();
  const enter = await request('enter',{code:issued.code}); assert.equal(enter.status,200);
  const customerCookie = enter.headers.get('set-cookie').split(';')[0];
  assert.match(customerCookie,/^osk_v2_customer=/);
  const baselineCustomerCookie = customerCookie.replace(/^osk_v2_customer=/,'osk_customer=');
  assert.equal((await (await request('event',undefined,baselineCustomerCookie)).json()).identified,false);
  assert.equal((await request('draw',{card:4},baselineCustomerCookie)).status,401);
  assert.equal((await request('admin-data',undefined,customerCookie)).status,401);
  assert.equal((await request('draw',{card:4})).status,401);
  const drawn = await (await request('draw',{card:4},customerCookie)).json(); assert.equal(drawn.prize.rank,1);
  const again = await (await request('draw',{card:8},customerCookie)).json(); assert.equal(again.id,drawn.id);
  assert.equal((await request('claim',{email:'http-test@example.com',consent:true},customerCookie)).status,200);
  const recovered = await (await request('event',undefined,customerCookie)).json(); assert.equal(recovered.result.claimed,true); assert.equal(recovered.result.email.includes('http-test'),false);
  const winners = (await (await request('admin-data',undefined,adminCookie)).json()).winners;
  assert.equal(winners[0].email,'http-test@example.com');
  assert.equal((await request('admin-fulfill',{id:drawn.id},adminCookie)).status,200);
  assert.equal((await request('event')).headers.get('cache-control'),'no-store');
  assert.equal((await request('event',undefined,customerCookie+'x')).status,200);
  assert.equal((await (await request('event',undefined,customerCookie+'x')).json()).identified,false);
  const leave = await request('leave',{},customerCookie);
  assert.equal(leave.status,200);
  assert.match(leave.headers.get('set-cookie'),/^osk_v2_customer=;/);
  assert.match(leave.headers.get('set-cookie'),/Max-Age=0/);
  const logout = await request('admin-logout',{},adminCookie);
  assert.equal(logout.status,200);
  assert.match(logout.headers.get('set-cookie'),/^osk_v2_admin=;/);
  assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
});
